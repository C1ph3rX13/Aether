async page => {
  const origin = new URL(page.url()).origin
  const assert = (condition, message) => { if (!condition) throw new Error(message) }
  const button = name => page.getByRole('button', { name, exact: true })
  const input = name => page.getByLabel(name, { exact: true })
  const creation = () => page.getByRole('dialog', { name: 'Create Project', exact: true })
  const guard = () => page.getByRole('dialog', { name: 'Unsaved settings', exact: true })
  const api = async (path, data, method = 'get') => {
    const response = await page.request[method](`${origin}/api/v1${path}`, data ? { data } : undefined)
    assert(response.ok(), `${method} ${path}: HTTP ${response.status()}`)
    return response.json()
  }
  const hold = async (pattern, method) => {
    let release, signal
    const held = new Promise(resolve => { release = resolve })
    const started = new Promise(resolve => { signal = resolve })
    await page.route(pattern, async route => {
      if (route.request().method() !== method) return route.continue()
      const response = await route.fetch()
      signal()
      await held
      await route.fulfill({ response })
    })
    return { started, finish: async () => { release(); await page.unrouteAll({ behavior: 'wait' }) } }
  }
  const sidebarCreateDisabled = () => page.locator('[data-slot="sidebar"] button').filter({ hasText: /^New Project$/ }).evaluate(element => element.disabled)
  const focusIs = name => button(name).evaluate(element => element === document.activeElement)
  let createRequests = 0
  const count = request => { if (request.method() === 'POST' && request.url() === `${origin}/api/v1/projects`) createRequests++ }
  page.on('request', count)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(`${origin}/projects`)
  await button('New Project').waitFor()
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(element => element.textContent === 'New Project')?.disabled)
  const navigation = page.getByRole('navigation', { name: 'Operations navigation', exact: true })
  const dimensions = await navigation.evaluate(element => {
    const container = element.closest('[data-slot="sidebar-container"]')
    const style = getComputedStyle(container)
    return { width: container.getBoundingClientRect().width, height: container.getBoundingClientRect().height, duration: style.transitionDuration, easing: style.transitionTimingFunction }
  })
  assert(dimensions.width === 288 && dimensions.height === 900 && dimensions.duration === '0.2s' && dimensions.easing === 'linear', 'Official 18rem / full viewport Sidebar and 200ms linear transition')
  assert(await navigation.getByLabel('Aether account placeholder').evaluate(element => !element.matches('button,a,[tabindex]') && !element.querySelector('button,a,[tabindex]')), 'Static Aether footer has no fake account interaction')
  assert(!(await navigation.innerText()).includes('@'), 'Static footer invents no email')
  for (const name of ['Inbox', 'Get Help', 'Search', 'Dashboard', 'Analytics', 'Team']) assert(!await navigation.getByText(name, { exact: true }).count(), `Demo ${name} removed`)
  assert(await navigation.getByRole('link').count() === 8, 'Only Projects, three Workers and three Settings category links are shown')
  assert(!await navigation.getByRole('button', { name: 'Workers', exact: true }).count(), 'Worker branches stay visible without a collapse trigger')
  const spacing = await navigation.evaluate(element => {
    const content = element.querySelector('[data-slot="sidebar-content"]')
    const rows = ['/workers/codex', '/workers/claude', '/workers/pi'].map(path => content.querySelector(`a[href="${path}"]`).getBoundingClientRect())
    const tasks = content.querySelector('a[href="/settings/task-timeouts"]').getBoundingClientRect()
    const labels = [...content.querySelectorAll('[data-slot="sidebar-group-label"]')].map(label => label.textContent)
    const workerLabel = content.querySelector('[data-slot="sidebar-group-label"]').getBoundingClientRect()
    const projects = content.querySelector('a[href="/projects"]').getBoundingClientRect()
    return { gaps: rows.slice(1).map((row, index) => row.top - rows[index].bottom), heights: rows.map(row => row.height), settingsGap: tasks.top - rows.at(-1).bottom, settingsBottom: content.lastElementChild.getBoundingClientRect().bottom, contentBottom: content.getBoundingClientRect().bottom, labels, workerLabelAfterProjects: workerLabel.top >= projects.bottom && workerLabel.bottom <= rows[0].top }
  })
  assert(spacing.heights.every(height => height === 32) && spacing.gaps.every(gap => gap === 4), 'Worker links use official 32px rows with 4px gaps')
  assert(spacing.labels.join(',') === 'Workers,Settings' && spacing.workerLabelAfterProjects, 'Visible Worker subtitle groups its branches between Projects and Settings')
  assert(await navigation.getByText('Workers', { exact: true }).isVisible(), 'Worker section subtitle is visible')
  assert(spacing.settingsGap >= 56 && Math.abs(spacing.settingsBottom - spacing.contentBottom) <= 1, 'B layout anchors Settings to the bottom of Sidebar content')
  await page.screenshot({ path: 'dist/frontend-catalog/sidebar-desktop.png' })
  await button('Toggle Sidebar').focus()
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => document.querySelector('[data-slot="sidebar-container"]').getBoundingClientRect().right <= 0)
  assert(await navigation.evaluate(element => element.inert), 'Collapsed desktop Sidebar cannot retain hidden tab stops')
  await page.keyboard.press('Control+b')
  await page.waitForFunction(() => document.querySelector('[data-slot="sidebar-gap"]').getBoundingClientRect().width === 288)
  for (const [name, path] of [['Codex', '/workers/codex'], ['Claude', '/workers/claude'], ['Pi', '/workers/pi'], ['Tasks', '/settings/task-timeouts'], ['Runtime', '/settings/project-runtime'], ['Prompts', '/settings/prompt-group']]) {
    await navigation.getByRole('link', { name, exact: true }).click()
    await page.waitForURL(`${origin}${path}`)
    assert(await navigation.getByRole('link', { name, exact: true }).getAttribute('aria-current') === 'page', `${name} has its real active route`)
    await button('New Project').click()
    await creation().getByLabel('Title', { exact: true }).waitFor()
    assert(await creation().getByLabel('Title', { exact: true }).evaluate(element => element === document.activeElement), 'Creation opens with form focus from every page')
    await creation().getByRole('button', { name: 'Cancel', exact: true }).click()
    assert(await focusIs('New Project'), 'Desktop cancellation restores the primary Sidebar action')
  }
  await page.setViewportSize({ width: 1024, height: 390 })
  await navigation.getByRole('link', { name: 'Prompts', exact: true }).focus()
  assert(await navigation.getByRole('link', { name: 'Prompts', exact: true }).evaluate(element => element.getBoundingClientRect().bottom <= innerHeight), 'Short viewport scrolls to the lowest Settings destination')
  assert(await navigation.getByLabel('Aether account placeholder').isVisible(), 'Short viewport retains the static footer')
  await page.screenshot({ path: 'dist/frontend-catalog/sidebar-short.png' })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(`${origin}/settings/task-timeouts`)
  await input('Reason primary (seconds)').fill('777')
  await button('New Project').click()
  await guard().getByRole('button', { name: 'Cancel', exact: true }).click()
  assert(await input('Reason primary (seconds)').inputValue() === '777' && createRequests === 0 && await focusIs('New Project'), 'Dirty Cancel preserves the page, edits and creation trigger without a POST')
  await button('New Project').click()
  const save = await hold('**/api/v1/configuration', 'PUT')
  try {
    await guard().getByRole('button', { name: 'Save', exact: true }).click()
    await save.started
    assert(await sidebarCreateDisabled() && createRequests === 0, 'Pending Save prevents global creation before the save result')
  } finally { await save.finish() }
  await creation().getByLabel('Title', { exact: true }).waitFor()
  assert((await api('/configuration')).draft.tasks.reason.primary_seconds === 777, 'Save happens before creating the Project')
  await creation().getByRole('button', { name: 'Cancel', exact: true }).click()

  // Concurrent public API Save creates an actual stale-version failure.
  const concurrent = await api('/configuration')
  for (const worker of concurrent.draft.workers) delete worker.secrets
  concurrent.draft.tasks.reason.primary_seconds = 778
  await api('/configuration', { expected_draft_version: concurrent.draft_version, draft: concurrent.draft }, 'put')
  await input('Reason primary (seconds)').fill('779')
  await button('New Project').click()
  const conflictResponse = page.waitForResponse(response => response.url().endsWith('/api/v1/configuration') && response.request().method() === 'PUT')
  await guard().getByRole('button', { name: 'Save', exact: true }).click()
  assert((await conflictResponse).status() === 409, 'Dirty Save fails at the real CAS boundary')
  const conflict = page.getByRole('dialog', { name: 'Settings changed elsewhere', exact: true })
  await conflict.getByRole('button', { name: 'Keep editing', exact: true }).click()
  assert(createRequests === 0 && !await creation().count() && await input('Reason primary (seconds)').inputValue() === '779', 'Failed Save keeps edits and makes no creation request')
  await button('New Project').click()
  await guard().getByRole('button', { name: 'Discard', exact: true }).click()
  await creation().getByLabel('Title', { exact: true }).waitFor()
  assert(await input('Reason primary (seconds)').inputValue() === '777', 'Discard restores the local saved baseline before creation')
  await creation().getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.goto(`${origin}/settings/runtime-capacity`)
  await input('Scheduler interval (seconds)').waitFor()

  await input('Scheduler interval (seconds)').fill('8')
  await page.setViewportSize({ width: 390, height: 844 })
  await button('Toggle Sidebar').click()
  let mobileNavigation = page.getByRole('dialog', { name: 'Operations navigation', exact: true })
  await mobileNavigation.getByRole('button', { name: 'New Project', exact: true }).click()
  await mobileNavigation.waitFor({ state: 'hidden' })
  await guard().getByRole('button', { name: 'Cancel', exact: true }).click()
  assert(await input('Scheduler interval (seconds)').inputValue() === '8' && await focusIs('Toggle Sidebar'), 'Mobile dirty Cancel returns focus to Toggle Sidebar and keeps edits')
  await button('Toggle Sidebar').click()
  await mobileNavigation.getByRole('button', { name: 'New Project', exact: true }).click()
  await guard().getByRole('button', { name: 'Discard', exact: true }).click()
  await creation().getByLabel('Title', { exact: true }).waitFor()
  assert(await creation().getByLabel('Title', { exact: true }).evaluate(element => element === document.activeElement), 'Mobile dirty Discard opens creation after the guard closes')
  await creation().getByRole('button', { name: 'Cancel', exact: true }).click()
  assert(await focusIs('Toggle Sidebar'), 'Mobile creation cancellation restores Toggle Sidebar after dirty resolution')
  await page.setViewportSize({ width: 1440, height: 900 })

  // The existing Worker edit uses the same guard for a global action.
  await page.goto(`${origin}/workers/codex/editor?worker=onboarding-worker`)
  await input('Worker name').waitFor()
  await input('Priority').fill('9')
  await button('New Project').click()
  await guard().getByRole('button', { name: 'Cancel', exact: true }).click()
  assert(await input('Priority').inputValue() === '9' && createRequests === 0, 'Worker dirty Cancel preserves input')
  await button('New Project').click()
  await guard().getByRole('button', { name: 'Discard', exact: true }).click()
  await creation().waitFor()
  await creation().getByRole('button', { name: 'Cancel', exact: true }).click()

  await page.goto(`${origin}/workers/pi`)
  await page.setViewportSize({ width: 390, height: 844 })
  await button('Toggle Sidebar').click()
  const sheet = page.getByRole('dialog', { name: 'Operations navigation', exact: true })
  await sheet.waitFor()
  await page.screenshot({ path: 'dist/frontend-catalog/sidebar-phone.png', animations: 'disabled' })
  for (const control of [sheet.getByRole('button', { name: 'New Project', exact: true }), ...['Projects', 'Codex', 'Tasks'].map(name => sheet.getByRole('link', { name, exact: true }))]) {
    await control.focus()
    await page.keyboard.press('Escape')
    await sheet.waitFor({ state: 'hidden' })
    assert(await focusIs('Toggle Sidebar'), 'A single Escape from a focused mobile navigation control closes the Sheet and restores its trigger')
    await button('Toggle Sidebar').click()
    await sheet.waitFor()
  }
  await sheet.getByRole('button', { name: 'New Project', exact: true }).click()
  await sheet.waitFor({ state: 'hidden' })
  await creation().getByLabel('Title', { exact: true }).waitFor()
  assert(await creation().getByLabel('Title', { exact: true }).evaluate(element => element === document.activeElement), 'Mobile Sheet closes before creation focus enters the Dialog')
  await creation().getByRole('button', { name: 'Cancel', exact: true }).click()
  assert(await focusIs('Toggle Sidebar'), 'Mobile cancellation restores Toggle Sidebar')
  await button('Toggle Sidebar').click()
  await sheet.getByRole('button', { name: 'New Project', exact: true }).click()
  for (const [name, value] of [['Title', 'Global Sidebar Project'], ['Origin', 'Known global evidence'], ['Goal', 'Verify global creation']]) await creation().getByLabel(name, { exact: true }).fill(value)
  await creation().getByRole('button', { name: 'Add Hint', exact: true }).click()
  await creation().getByLabel('Hint 1', { exact: true }).fill('Global creation Hint')
  // Drop only this request before it reaches the server, then explicitly retry.
  await page.route('**/api/v1/projects', route => route.request().method() === 'POST' ? route.abort('connectionfailed') : route.continue())
  await creation().getByRole('button', { name: 'Create Project', exact: true }).click()
  await creation().getByRole('alert').waitFor()
  assert(await creation().getByLabel('Title', { exact: true }).inputValue() === 'Global Sidebar Project', 'Failed creation keeps the complete form')
  await page.unroute('**/api/v1/projects')
  const receipt = page.waitForResponse(response => response.url().endsWith('/api/v1/projects') && response.request().method() === 'POST')
  await creation().getByRole('button', { name: 'Create Project', exact: true }).click()
  const response = await receipt
  const result = await response.json()
  await page.waitForURL(`${origin}/projects/${result.project.id}`)
  await page.getByRole('heading', { name: 'Global Sidebar Project', exact: true }).waitFor()
  assert(result.project.bootstrap_enabled && result.hints[0].creator === 'catalog-operator' && !('operator' in response.request().postDataJSON()), 'Global creation preserves default Bootstrap, Initial Hints and server-owned identity')
  await page.waitForFunction(() => document.activeElement?.id === 'main-content')
  assert(createRequests === 2, 'Exactly one failed attempt and one explicit retry')
  await api(`/projects/${result.project.id}/actions/delete`, { expected_title: result.project.title, expected_revision: result.project.revision }, 'post')
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(`${origin}/projects`)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await button('Toggle Sidebar').click()
  assert(await page.locator('[data-slot="sidebar-container"]').evaluate(element => getComputedStyle(element).transitionDuration === '0s'), 'Reduced motion disables offcanvas movement')
  await button('Toggle Sidebar').click()
  await page.evaluate(() => document.documentElement.style.fontSize = '200%')
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Sidebar and main content fit at 200% text')
  await page.evaluate(() => document.documentElement.style.fontSize = '')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  page.off('request', count)
  return { officialSidebar: 'passed', globalCreation: 'passed', guardedDirtyCreation: 'passed', busyExclusion: 'passed', mobileFocus: 'passed', singleEscape: 'passed', shortViewportAndReducedMotion: 'passed' }
}
