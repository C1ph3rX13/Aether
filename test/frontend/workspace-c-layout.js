async page => {
  const assert = (condition, message) => { if (!condition) throw new Error(message) }
  const origin = new URL(page.url()).origin
  assert(new URL(origin).port !== '8000', 'Acceptance writes require an isolated backend')
  const api = async (path, data, method = 'get') => {
    const response = await page.request[method](`${origin}/api/v1${path}`, data ? { data } : undefined)
    assert(response.ok(), `${method} ${path}: ${response.status()} ${await response.text()}`)
    return response.json()
  }
  const live = () => page.getByLabel('Data Freshness: Live', { exact: true }).waitFor()
  const title = `C layout acceptance ${Date.now()}`
  let detail = await api('/projects', { title, origin: 'Known Origin', goal: 'Verify persisted graph relationships', bootstrap_enabled: true }, 'post')
  const id = detail.project.id
  const path = `/projects/${id}`
  const expectedEdges = value => value.intents.reduce((count, intent) => count + intent.from.length + (intent.to ? 1 : 0), 0) + value.facts.filter(fact => fact.supersedes).length
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(`${origin}${path}`)
  await live()
  const graph = page.getByRole('application', { name: 'Blackboard graph', exact: true })
  const inspection = page.getByRole('dialog', { name: 'Project inspection', exact: true })
  assert(!await inspection.isVisible(), 'Inspection defaults closed')
  assert(await graph.locator('.react-flow__node').evaluateAll(nodes => nodes.every(node => node.offsetWidth === 240 && node.offsetHeight === 160)), 'Existing native node dimensions remain 240 × 160')
  const canvas = await page.getByTestId('project-canvas').boundingBox()
  assert(canvas.width === 1096 && canvas.height === 688, 'C canvas uses the approved desktop footprint')
  const buttons = await page.locator('[data-slot="button"]:visible').filter({ hasNot: page.locator('[data-slot="sidebar-menu-button"]') }).evaluateAll(items => items.every(button => button.offsetHeight === 36))
  assert(buttons, 'Application buttons use native 36px size')
  assert(await page.getByRole('button', { name: 'Toggle Sidebar', exact: true }).evaluate(button => button.offsetHeight === 28), 'SidebarTrigger retains official 28px')
  const originNode = graph.locator('.react-flow__node').filter({ has: page.getByRole('button', { name: 'Open Fact origin', exact: true }) })
  const details = originNode.getByRole('button', { name: 'Open Fact origin', exact: true })
  const evidence = originNode.getByRole('checkbox', { name: 'Select origin as Completion Evidence', exact: true })
  assert(await graph.locator('.react-flow__node').evaluateAll(nodes => nodes.every(node => node.tabIndex < 0)), 'Graph wrappers introduce no inert keyboard stops')
  await details.focus()
  await page.keyboard.press('Enter')
  await inspection.waitFor()
  await page.keyboard.press('Escape')
  await inspection.waitFor({ state: 'hidden' })
  assert(await details.evaluate(button => button === document.activeElement), 'Keyboard inspection restores Details focus')
  await page.keyboard.press('Tab')
  assert(await evidence.evaluate(checkbox => checkbox === document.activeElement), 'Tab goes directly from Details to Completion Evidence')
  await page.keyboard.press('Space')
  await page.waitForFunction(() => document.getElementById('evidence-origin').getAttribute('aria-checked') === 'true')
  assert(!await inspection.isVisible(), 'Selecting evidence does not open inspection')
  await originNode.getByText('Known Origin', { exact: true }).click()
  await inspection.waitFor()
  await page.keyboard.press('Escape')
  await inspection.waitFor({ state: 'hidden' })
  assert(await details.evaluate(button => button === document.activeElement), 'Pointer inspection restores the native Details button')
  assert(await evidence.isChecked(), 'Inspection preserves Completion Evidence selection')
  await page.screenshot({ path: 'dist/frontend-catalog/workspace-keyboard-desktop.png', animations: 'disabled' })
  for (const viewport of [{ width: 390, height: 844 }, { width: 320, height: 568 }]) {
    await page.setViewportSize(viewport)
    await details.focus()
    await page.keyboard.press('Enter')
    await inspection.waitFor()
    await page.keyboard.press('Escape')
    await inspection.waitFor({ state: 'hidden' })
    assert(await details.evaluate(button => button === document.activeElement), `Details restores focus at ${viewport.width}px`)
    await page.keyboard.press('Tab')
    assert(await evidence.evaluate(checkbox => checkbox === document.activeElement), `Evidence follows Details at ${viewport.width}px`)
    assert(await evidence.isChecked(), 'Viewport changes preserve the explicit evidence selection')
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Graph page fits the mobile viewport')
    await page.screenshot({ path: `dist/frontend-catalog/workspace-keyboard-${viewport.width}.png`, animations: 'disabled' })
  }
  await page.setViewportSize({ width: 1440, height: 900 })
  await evidence.uncheck()
  await page.getByRole('button', { name: 'Toggle right inspection panel', exact: true }).click()
  await page.waitForFunction(() => Math.abs(document.getElementById('project-inspection').getBoundingClientRect().right - innerWidth) < 0.1)
  const bounds = await inspection.boundingBox()
  assert(bounds.width === 448 && bounds.x + bounds.width === 1440, 'Right Sheet uses the native approved width')
  await page.keyboard.press('Escape')
  await inspection.waitFor({ state: 'hidden' })
  assert(await page.getByRole('button', { name: 'Toggle right inspection panel', exact: true }).evaluate(button => button === document.activeElement), 'Inspection close restores trigger focus')
  await graph.getByRole('checkbox', { name: 'Select origin as Completion Evidence', exact: true }).focus()
  await page.keyboard.press('Space')
  await page.waitForFunction(() => document.getElementById('evidence-origin').getAttribute('aria-checked') === 'true')
  await page.getByRole('button', { name: 'Complete Project', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: 'Complete Project', exact: true })
  await dialog.getByLabel('Completion description', { exact: true }).fill('Explicitly reviewed Origin')
  await dialog.getByRole('button', { name: 'Complete Project', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  await live()
  detail = await api(path)
  assert(detail.project.status === 'completed', 'Lifecycle reflects authoritative completion')
  await page.waitForFunction(count => document.querySelectorAll('.react-flow__edge').length === count, expectedEdges(detail))
  assert(await graph.locator('.react-flow__edge').count() === expectedEdges(detail), 'Completion preserves all graph relationships')
  await page.getByRole('button', { name: 'Reopen', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Reopen Project', exact: true })
  await dialog.getByLabel('Reason for reopening', { exact: true }).fill('继续核实 — preserve operator input')
  await dialog.getByRole('button', { name: 'Reopen', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  await live()
  detail = await api(path)
  assert(detail.project.generation === 2 && detail.project.status === 'active', 'Reopen starts the next generation')
  await page.waitForFunction(count => document.querySelectorAll('.react-flow__edge').length === count, expectedEdges(detail))
  assert(await graph.locator('.react-flow__edge').count() === expectedEdges(detail), 'Reopen keeps every persisted relationship visible')
  await page.getByRole('button', { name: 'Snapshot', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Snapshot Blackboard', exact: true })
  await dialog.getByLabel('Format', { exact: true }).click()
  await page.getByRole('option', { name: 'JSON', exact: true }).click()
  await dialog.getByRole('button', { name: 'Export', exact: true }).click()
  const snapshot = JSON.parse(await dialog.getByLabel('Export result', { exact: true }).inputValue())
  assert(snapshot.project.revision === detail.project.revision, 'Snapshot exports the displayed revision')
  assert(await dialog.getByRole('button', { name: 'Close', exact: true }).count() === 1, 'Only the native X closes Snapshot')
  await page.keyboard.press('Escape')
  const second = await api('/projects', { title: `${title} second`, origin: 'Known Origin', goal: 'Verify bulk selection', bootstrap_enabled: false }, 'post')
  await page.goto(`${origin}/projects`)
  await page.getByLabel('Search Projects', { exact: true }).fill(title)
  const row = page.getByRole('row', { name: `Open ${title}`, exact: true })
  await row.getByRole('cell').nth(2).click()
  await page.waitForURL(`${origin}${path}`)
  await live()
  await page.goto(`${origin}/projects`)
  await page.getByLabel('Search Projects', { exact: true }).fill(title)
  await page.getByRole('button', { name: `Actions for ${title}`, exact: true }).click()
  assert(await page.getByRole('menuitem', { name: 'Open Project', exact: true }).locator('svg').count() === 1, 'Open Project uses a native icon')
  await page.keyboard.press('Escape')
  await page.getByRole('checkbox', { name: `Select ${title}`, exact: true }).check()
  await page.getByLabel('Search Projects', { exact: true }).fill('second')
  await page.getByRole('checkbox', { name: `Select ${title} second`, exact: true }).check()
  await page.getByRole('button', { name: 'Export selected', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Export selected Projects', exact: true })
  await dialog.getByLabel('Export result', { exact: true }).waitFor()
  const exports = JSON.parse(await dialog.getByLabel('Export result', { exact: true }).inputValue())
  assert(exports.length === 2 && exports.some(value => value.project.id === id && value.project.revision === detail.project.revision), 'Selected export loads latest backend states across filtering')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Delete selected', exact: true }).click()
  const deletion = page.getByRole('alertdialog', { name: 'Delete 2 selected Projects', exact: true })
  assert(await deletion.getByRole('button', { name: 'Delete Projects', exact: true }).isDisabled(), 'Bulk deletion requires every exact title')
  await deletion.getByLabel(`Confirm “${title}”`, { exact: true }).fill(title)
  await deletion.getByLabel(`Confirm “${title} second”`, { exact: true }).fill(`${title} second`)
  await deletion.getByRole('button', { name: 'Delete Projects', exact: true }).click()
  await deletion.waitFor({ state: 'hidden' })
  for (const projectId of [id, second.project.id]) assert((await page.request.get(`${origin}/api/v1/projects/${projectId}`)).status() === 404, 'Real selected deletion removes only test projects')
  await page.getByLabel('Search Projects', { exact: true }).fill('')
  return { cLayout: 'passed', nativeSizes: 'passed', graphKeyboard: 'passed', pointerInspectionFocus: 'passed', reopenRelationships: 'passed', selectedExport: 'passed', selectedDeletion: 'passed' }
}
